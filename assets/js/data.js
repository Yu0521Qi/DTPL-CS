/* 用「说话风格 + 口头禅」把通用反应库包装成某个客户专属的台词 */
function decorateLine(t, style, catchphrases) {
  const acts = (SPEAK_STYLES[style] || SPEAK_STYLES.terse).acts;
  const act = acts[Math.floor(Math.random() * acts.length)];
  let out = /^[（(]/.test(t) ? t : act + t;
  if (catchphrases && catchphrases.length && Math.random() < 0.35) {
    out = catchphrases[Math.floor(Math.random() * catchphrases.length)] + '，' + out;
  }
  return out;
}

function makeReactions(style, catchphrases) {
  const rx = {};
  Object.keys(GENERIC_REACTIONS).forEach(k => {
    rx[k] = {};
    ['good', 'mid', 'bad'].forEach(lv => {
      rx[k][lv] = (GENERIC_REACTIONS[k][lv] || []).map(t => decorateLine(t, style, catchphrases));
    });
  });
  return rx;
}

/* 把用户填的「禁忌关键词」转成可用的正则（自动转义） */
function keywordsToRegExp(str) {
  const keys = String(str || '').split(/[,，、\s]+/).map(s => s.trim()).filter(Boolean);
  if (!keys.length) return null;
  const esc = s => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  return new RegExp(keys.map(esc).join('|'));
}

