/* 根据产品名称+品类，匹配最接近的品类知识库 */
function matchCategory(basic) {
  const t = ((basic.category || '') + ' ' + (basic.name || '')).toLowerCase();
  if (/精酿|啤酒|鲜啤|小麦|ipa|世涛|果啤|扎啤|生啤|原浆|精酿啤酒/.test(t)) return CATEGORY_KB.beer;
  if (/光瓶|口粮|玻汾|老村长|牛栏山|乡镇|社区|自饮|大排档|工地/.test(t)) return CATEGORY_KB.guangping;
  if (/低度|果酒|梅酒|米酒|清酒|利口|起泡|年轻|悦己|果味|微醺|女士/.test(t)) return CATEGORY_KB.low;
  if (/白|浓香|酱香|清香|宴席|送礼|商务|年份|窖|曲酒|烧酒/.test(t)) return CATEGORY_KB.baijiu;
  return CATEGORY_KB.generic;
}

/* 离线生成：根据基本信息 + 品类知识库，生成政策与 FABE 卖点（纯函数，无 DOM 依赖） */
function genOfflineContent(basic) {
  const cost = Number(basic.cost) || 0;
  const retail = Number(basic.retail) || 0;
  const gap = Math.max(0, Math.round((retail - cost) * 100) / 100);
  const rate = retail ? Math.round(gap / retail * 1000) / 10 : 0;
  const n = 10;
  const n1 = n + 1;
  const m = gap ? Math.round(gap * 4 * 30) : 0; // 一天卖 4 瓶的月毛利示例
  const ctx = {
    cost, retail, gap, rate, spec: basic.spec || '标准规格', scene: basic.scene || '终端门店', n, n1, m
  };
  const fill = s => String(s).replace(/\{(\w+)\}/g, (_, k) =>
    (ctx[k] === undefined || ctx[k] === '') ? (k === 'm' ? '一笔稳定' : '') : ctx[k]);
  const cat = matchCategory(basic);
  return {
    category: cat.name,
    policies: cat.policies.map(fill),
    fabeF: cat.fabe.F.map(fill),
    fabeA: cat.fabe.A.map(fill),
    fabeB: cat.fabe.B.map(fill),
    fabeE: cat.fabe.E.map(fill)
  };
}
